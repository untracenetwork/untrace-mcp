#!/usr/bin/env node
// Embed the Drive SDK guide (guide/sdk-readme.md: the untrace-sdk 2.0.0 README without its
// "How ... works" internals notes, with the secret shown as a placeholder) into
// src/generated/guide.ts as named sections, so untrace_setup_guide works offline.
// Runs before build, typecheck and test.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

const root = fileURLToPath(new URL("../", import.meta.url))
const md = readFileSync(`${root}guide/sdk-readme.md`, "utf8").replace(/\r\n/g, "\n")

// Split on level-2 headings. Fenced code blocks never start with "## ".
const sections = {}
let current = "intro"
let buf = []
for (const line of md.split("\n")) {
  const m = /^## (.+)$/.exec(line)
  if (m) {
    sections[current] = buf.join("\n").trim()
    current = m[1].trim()
    buf = []
  } else buf.push(line)
}
sections[current] = buf.join("\n").trim()

// Only the sections an app developer needs. Development, release and contract notes are left out.
const pick = {
  intro: "intro",
  createKey: "1. Create a key in Drive",
  core: "2. Core client",
  next: "3. Next.js",
  browser: "4. React and Vue",
  scopes: "Scopes and roles",
  errors: "Errors",
  security: "Security notes",
}
const out = {}
for (const [key, heading] of Object.entries(pick)) {
  const body = sections[heading]
  if (!body) {
    console.error(`embed-guide: section "${heading}" not found in guide/sdk-readme.md`)
    process.exit(1)
  }
  if (/\u2014/.test(body)) {
    console.error(`embed-guide: section "${heading}" contains an em dash`)
    process.exit(1)
  }
  out[key] = body
}

mkdirSync(`${root}src/generated`, { recursive: true })
writeFileSync(
  `${root}src/generated/guide.ts`,
  "// Generated by scripts/embed-guide.mjs from guide/sdk-readme.md. Do not edit.\n" +
    `export const SDK_GUIDE = ${JSON.stringify(out, null, 2)} as const\n`
)
console.log(`embed-guide: ${Object.keys(out).length} sections embedded`)
