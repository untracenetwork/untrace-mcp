#!/usr/bin/env node
// Embed the Drive SDK README (guide/sdk-readme.md, copied from @untracenetwork/sdk 1.0.0) into
// src/generated/guide.ts as named sections, so untrace_setup_guide works offline and matches
// the SDK version this server depends on. Runs before build, typecheck and test.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

const root = fileURLToPath(new URL("../", import.meta.url))
const md = readFileSync(`${root}guide/sdk-readme.md`, "utf8").replace(/\r\n/g, "\n")

// Split on level-2 headings. Fenced code blocks never start with "## ".
const sections = {}
let current = "intro"
let buf = []
for (const line of md.split("\n")) {
  const m = /^## (.+)$/.exec(line)
  if (m) {
    sections[current] = buf.join("\n").trim()
    current = m[1].trim()
    buf = []
  } else buf.push(line)
}
sections[current] = buf.join("\n").trim()

// Only the sections an app developer needs. Development, release and self-hosting notes are left out.
const pick = {
  intro: "intro",
  createKey: "1. Create a key in Drive",
  next: "2. Next.js quick start",
  node: "3. Node.js",
  browser: "4. React and Vue",
  scopes: "Scopes and roles",
  metering: "Metering",
  errors: "Errors",
}
const out = {}
for (const [key, heading] of Object.entries(pick)) {
  const body = sections[heading]
  if (!body) {
    console.error(`embed-guide: section "${heading}" not found in guide/sdk-readme.md`)
    process.exit(1)
  }
  if (/\u2014/.test(body)) {
    console.error(`embed-guide: section "${heading}" contains an em dash`)
    process.exit(1)
  }
  out[key] = body
}

mkdirSync(`${root}src/generated`, { recursive: true })
writeFileSync(
  `${root}src/generated/guide.ts`,
  "// Generated by scripts/embed-guide.mjs from guide/sdk-readme.md. Do not edit.\n" +
    `export const SDK_GUIDE = ${JSON.stringify(out, null, 2)} as const\n`
)
console.log(`embed-guide: ${Object.keys(out).length} sections embedded`)
